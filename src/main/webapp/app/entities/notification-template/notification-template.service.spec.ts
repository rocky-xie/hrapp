import { beforeEach, describe, expect, it, vi } from 'vitest';

import axios from 'axios';

import { NotificationTemplate } from '@/shared/model/notification-template.model';

import NotificationTemplateService from './notification-template.service';

const error = {
  response: {
    status: null,
    data: {
      type: null,
    },
  },
};

const axiosStub = {
  get: vi.spyOn(axios, 'get'),
  post: vi.spyOn(axios, 'post'),
  put: vi.spyOn(axios, 'put'),
  patch: vi.spyOn(axios, 'patch'),
  delete: vi.spyOn(axios, 'delete'),
};

describe('Service Tests', () => {
  describe('NotificationTemplate Service', () => {
    let service: NotificationTemplateService;
    let elemDefault;

    beforeEach(() => {
      service = new NotificationTemplateService();
      elemDefault = new NotificationTemplate(123, 'AAAAAAA', 'GRADUATE', 'AAAAAAA', 0, 'AAAAAAA', 'AAAAAAA', false, false);
    });

    describe('Service methods', () => {
      it('should find an element', async () => {
        const returnedFromService = { ...elemDefault };
        axiosStub.get.mockResolvedValue({ data: returnedFromService });

        return service.find(123).then(res => {
          expect(res).toMatchObject(elemDefault);
        });
      });

      it('should not find an element', async () => {
        axiosStub.get.mockRejectedValue(error);
        return service
          .find(123)
          .then()
          .catch(err => {
            expect(err).toMatchObject(error);
          });
      });

      it('should create a NotificationTemplate', async () => {
        const returnedFromService = { id: 123, ...elemDefault };
        const expected = { ...returnedFromService };

        axiosStub.post.mockResolvedValue({ data: returnedFromService });
        return service.create({}).then(res => {
          expect(res).toMatchObject(expected);
        });
      });

      it('should not create a NotificationTemplate', async () => {
        axiosStub.post.mockRejectedValue(error);

        return service
          .create({})
          .then()
          .catch(err => {
            expect(err).toMatchObject(error);
          });
      });

      it('should update a NotificationTemplate', async () => {
        const returnedFromService = {
          eventType: 'BBBBBB',
          recruitmentType: 'BBBBBB',
          language: 'BBBBBB',
          versionNumber: 1,
          subjectTemplate: 'BBBBBB',
          bodyTemplate: 'BBBBBB',
          externalSafe: true,
          published: true,
          ...elemDefault,
        };

        const expected = { ...returnedFromService };
        axiosStub.put.mockResolvedValue({ data: returnedFromService });

        return service.update(expected).then(res => {
          expect(res).toMatchObject(expected);
        });
      });

      it('should not update a NotificationTemplate', async () => {
        axiosStub.put.mockRejectedValue(error);

        return service
          .update({})
          .then()
          .catch(err => {
            expect(err).toMatchObject(error);
          });
      });

      it('should partial update a NotificationTemplate', async () => {
        const patchObject = { versionNumber: 1, subjectTemplate: 'BBBBBB', externalSafe: true, ...new NotificationTemplate() };
        const returnedFromService = Object.assign(patchObject, elemDefault);

        const expected = { ...returnedFromService };
        axiosStub.patch.mockResolvedValue({ data: returnedFromService });

        return service.partialUpdate(patchObject).then(res => {
          expect(res).toMatchObject(expected);
        });
      });

      it('should not partial update a NotificationTemplate', async () => {
        axiosStub.patch.mockRejectedValue(error);

        return service
          .partialUpdate({})
          .then()
          .catch(err => {
            expect(err).toMatchObject(error);
          });
      });

      it('should return a list of NotificationTemplate', async () => {
        const returnedFromService = {
          eventType: 'BBBBBB',
          recruitmentType: 'BBBBBB',
          language: 'BBBBBB',
          versionNumber: 1,
          subjectTemplate: 'BBBBBB',
          bodyTemplate: 'BBBBBB',
          externalSafe: true,
          published: true,
          ...elemDefault,
        };
        const expected = { ...returnedFromService };
        axiosStub.get.mockResolvedValue([returnedFromService]);
        return service.retrieve({ sort: {}, page: 0, size: 10 }).then(res => {
          expect(res).toContainEqual(expected);
        });
      });

      it('should not return a list of NotificationTemplate', async () => {
        axiosStub.get.mockRejectedValue(error);

        return service
          .retrieve()
          .then()
          .catch(err => {
            expect(err).toMatchObject(error);
          });
      });

      it('should delete a NotificationTemplate', async () => {
        axiosStub.delete.mockResolvedValue({ ok: true });
        return service.delete(123).then(res => {
          expect(res.ok).toBeTruthy();
        });
      });

      it('should not delete a NotificationTemplate', async () => {
        axiosStub.delete.mockRejectedValue(error);

        return service
          .delete(123)
          .then()
          .catch(err => {
            expect(err).toMatchObject(error);
          });
      });
    });
  });
});
